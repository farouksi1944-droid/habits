export function getDailyMotivationalQuote(date: Date = new Date()): MotivationalQuote {
  const localDayNumber = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000
  );
  const index =
    ((localDayNumber % MOTIVATIONAL_QUOTES.length) + MOTIVATIONAL_QUOTES.length) %
    MOTIVATIONAL_QUOTES.length;
  return MOTIVATIONAL_QUOTES[index];
}
